/**
 * 통합 작성 폼이 쓰는 값이다.
 *
 * 점주가 한 폼에서 종류를 고르고, 그 종류가 가진 카테고리 가운데에서 자기 건을 고른다. 목록이
 * 바뀌면 이 파일만 고친다.
 */

/**
 * 이 폼이 접수할 수 있는 두 채널이다.
 *
 * 이름이 셋이고 문장이 하나다. `menu` 는 앱의 메뉴와 헤더가 쓰는 이름, `choice` 는 점주가 종류를
 * 고를 때 읽는 말, `example` 은 그 종류에 무엇이 드는지 보여 주는 보기이며, `handling` 은 고른 뒤에
 * 무슨 일이 일어나는지 알리는 후속 문장이다. 「점주의 소리」와 「지원요청」은 본사가 채널을 부르는 이름이라, 점주는 그 둘이
 * 무엇을 담는 자리인지 알고 있어야 고를 수 있다. 무엇을 하려는지로 적으면 자기 상황을 읽고
 * 고른다. 오입을 줄이는 것이 이 폼의 일이므로 고르는 자리에는 뒤쪽 이름을 쓴다.
 */
export const CHANNELS = [
  {
    value: "request",
    menu: "지원요청",
    choice: "발생한 문제 처리 요청",
    example: "오배송, 불량, 발주 오류, 시스템 오류 등 지금 겪는 문제",
    // 담당 SV 가 기본 처리 담당자다. 상세에 채팅 탭이 있어 그 자리에서 주고받는다.
    handling: "담당 SV가 처리하며, 채팅으로 이야기할 수 있습니다.",
  },
  {
    value: "voice",
    menu: "점주의 소리",
    choice: "본사에 제안·의견",
    example: "정책, 메뉴, 제도 개선 등 본사가 검토할 의견",
    // 확인 전 자리 표시다. 등록한 뒤의 흐름을 아직 받지 못했다. 일부가 지원요청으로 전환되므로,
    // 그 사실을 점주에게 미리 알릴지도 함께 정해야 한다.
    handling: "본사가 검토한 뒤 결과를 알려 드립니다.",
  },
] as const;

export type Channel = (typeof CHANNELS)[number]["value"];

/** 앱의 메뉴와 헤더가 쓰는 이름이다. */
export function menuLabel(channel: Channel) {
  return CHANNELS.find((item) => item.value === channel)?.menu ?? "";
}

/** 고른 뒤에 무슨 일이 일어나는지 알리는 후속 문장이다. */
export function handlingNote(channel: Channel) {
  return CHANNELS.find((item) => item.value === channel)?.handling ?? "";
}

/**
 * 카테고리는 종류마다 따로 둔다. 두 채널이 카테고리에 묻는 것이 서로 다르기 때문이다.
 *
 * 지원요청의 카테고리는 그 건을 어느 팀이 처리할지를 정하는 배분 키이므로 「무슨 문제가 났는가」를
 * 묻고, 점주의 소리의 카테고리는 본사가 검토할 때 건들을 묶어 보는 축이므로 「무엇에 관한
 * 의견인가」를 묻는다. 묻는 것이 다르면 답의 이름도 달라야 하며, 두 목록에 같은 이름을 두지 않는
 * 것이 그 구분을 지키는 방법이다.
 *
 * 한 벌을 두 채널이 함께 쓰던 것을 갈랐다. 함께 쓰면 종류를 바꿔도 아래가 그대로라, 종류를 고르는
 * 일이 화면에서 무슨 일을 하는지 보이지 않는다. 갈라 두면 양쪽에 있는 이름을 보고 점주가 종류를
 * 잘못 고른다는 우려가 있었으나, 그것은 두 목록을 나란히 놓고 볼 때의 이야기다. 이 화면은 종류를
 * 고른 뒤에야 카테고리를 세우므로 점주가 두 목록을 동시에 보지 않는다.
 *
 * 두 목록 모두 「기타」가 마지막이며, 그 비율이 높아지면 목록이 현실을 담지 못한다는 신호다. 본사가
 * 접수 후에 카테고리를 고쳐 다시 배분할 수 있어야 한다.
 *
 * 프로토타입이므로 이름과 경계는 조직도를 받은 뒤에 다시 짠다.
 */

/**
 * 지원요청의 카테고리다. 지금 겪고 있는 문제를 그 종류로 가른다.
 *
 * 무엇에 대한 건인지가 아니라 무슨 일이 일어났는지로 적는다. 점주는 자기 매장에서 벌어진 일을
 * 들고 오므로 그 일의 이름을 찾는 편이 빠르고, 본사 쪽에서도 처리할 팀이 그 이름에서 곧바로
 * 갈린다. 「발주·정산」처럼 둘을 묶은 자리는 담당이 갈리면 쪼갠다.
 */
const REQUEST_CATEGORIES = ["배송·결품", "제품 불량", "발주·정산", "기기·시설", "앱 오류", "배달", "기타"];

/**
 * 점주의 소리의 카테고리다. 무엇에 관한 의견인지만 굵게 가른다.
 *
 * 지원요청보다 성기게 두는 까닭은 접수 시점에 담당을 가를 필요가 없기 때문이다. 본사가 검토한 뒤
 * 답하는 건이므로 카테고리는 검토할 때 묶어 보는 축이면 충분하고, 세분화하면 고르는 사람만
 * 고민이 길어진다. 접수 후에 본사가 고칠 수 있다는 점도 목록을 굵게 두는 근거다.
 */
const VOICE_CATEGORIES = ["메뉴", "운영", "물류", "마케팅", "사장님 앱", "기타"];

/** 고른 종류가 가진 카테고리 한 벌이다. */
export function categoriesOf(channel: Channel) {
  return channel === "request" ? REQUEST_CATEGORIES : VOICE_CATEGORIES;
}
